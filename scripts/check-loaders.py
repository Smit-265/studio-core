#!/usr/bin/env python3
"""check-loaders.py - the game repo's .claude/ loaders match studio-core.

A game repo does not copy studio-core's agents, commands and skills; it carries
a LOADER for each one. A loader holds its own frontmatter and an instruction to
read the real definition from studio-core. No behaviour lives in a loader.
See DECISIONS.md D-003.

Copies fork, so drift is the one real risk. This makes drift a build failure:

    check-loaders.py [project-path]     default: cwd
      --write     regenerate loaders instead of checking (sync-loaders.sh)
      --quiet     only print failures

Checks: every studio-core definition has a loader | no loader without a source |
frontmatter matches the source | body is the canonical loader body |
.claude/settings.json (the hook wiring) matches templates/game-settings.json.

Generation and checking share one renderer below, so the two cannot disagree.

Exit: 0 in sync | 1 drifted, missing or extra | 2 the check could not run.
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from _sclib import (  # noqa: E402
    EXIT_CONFIG,
    EXIT_OK,
    Report,
    bold,
    find_studio_core,
    green,
)

# Frontmatter keys copied to the loader. `model` is included because model
# selection happens at invocation, before anything reads the definition, so it
# cannot be deferred upstream the way behaviour can.
FRONTMATTER_KEYS = ("name", "description", "tools", "model", "argument-hint", "allowed-tools")

# The hook wiring travels with the loaders: same generator, same drift check,
# so a game repo cannot quietly run without the guards. Source of truth is
# templates/game-settings.json; the file is copied byte-for-byte.
SETTINGS_REL = ".claude/settings.json"
SETTINGS_SRC = "templates/game-settings.json"


def split_frontmatter(text: str, where: str) -> tuple[dict, str]:
    """Return (frontmatter, body). Deliberately not YAML: values are scalars and
    a full parser would accept shapes the loader format does not support."""
    if not text.startswith("---"):
        raise ValueError(f"{where}: no frontmatter block (file must start with ---)")
    end = text.find("\n---", 3)
    if end == -1:
        raise ValueError(f"{where}: frontmatter block is not closed")
    fm: dict[str, str] = {}
    for line in text[3:end].splitlines():
        line = line.strip()
        if not line or line.startswith("#"):
            continue
        if ":" not in line:
            raise ValueError(f"{where}: frontmatter line is not `key: value`: {line!r}")
        key, _, value = line.partition(":")
        fm[key.strip()] = value.strip()
    body = text[end + 4:].lstrip("\n")
    return fm, body


def loader_text(fm: dict, rel_source: str) -> str:
    """The canonical loader. One renderer for both --write and the check."""
    lines = ["---"]
    for key in FRONTMATTER_KEYS:
        if key in fm:
            lines.append(f"{key}: {fm[key]}")
    lines += [
        "---",
        "",
        f"# {fm.get('name', Path(rel_source).stem)}",
        "",
        "Loader. The definition lives in studio-core; this file carries no behaviour of its own.",
        "",
        "1. Resolve studio-core: `$STUDIO_CORE` if set, else `../studio-core`. See "
        "`DECISIONS.md` D-001.",
        f"2. Read `$STUDIO_CORE/{rel_source}`.",
        "3. Follow it exactly, with the working directory set to this repo.",
        "",
        "Generated by `sync-loaders.sh`. Do not edit: a loader has no content to change, and "
        "edits here are",
        "overwritten. Behaviour belongs upstream in studio-core.",
    ]
    return "\n".join(lines) + "\n"


def definitions(studio_core: Path) -> dict[str, Path]:
    """Map of repo-relative loader path -> studio-core source path."""
    found: dict[str, Path] = {}
    base = studio_core / ".claude"
    for sub in ("agents", "commands"):
        for src in sorted((base / sub).glob("*.md")):
            found[f".claude/{sub}/{src.name}"] = src
    for src in sorted((base / "skills").glob("*/SKILL.md")):
        found[f".claude/skills/{src.parent.name}/SKILL.md"] = src
    return found


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__,
                                 formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("project", nargs="?", default=".")
    ap.add_argument("--write", action="store_true", help="regenerate loaders")
    ap.add_argument("--quiet", action="store_true")
    args = ap.parse_args()

    project = Path(args.project).expanduser().resolve()
    if not project.is_dir():
        sys.stderr.write(f"error: project path does not exist: {project}\n")
        return EXIT_CONFIG

    studio_core = find_studio_core(project)
    if project == studio_core:
        # studio-core holds the definitions themselves; loaders would be circular.
        if not args.quiet:
            print(f"{green('loaders: OK')} - studio-core holds the definitions, not loaders")
        return EXIT_OK

    rep = Report("loaders")
    sources = definitions(studio_core)
    if not sources:
        rep.error(f"no agent, command or skill definitions found under {studio_core}/.claude/")
        return rep.finish()

    if not args.quiet and not args.write:
        print(f"{bold('loaders')}  {project}/.claude  ({len(sources)} definition(s))")

    written = 0
    for rel, src in sorted(sources.items()):
        target = project / rel
        try:
            src_fm, _ = split_frontmatter(src.read_text(encoding="utf-8"), str(src))
        except ValueError as exc:
            rep.error(f"studio-core source is malformed: {exc}")
            continue

        expected = loader_text(src_fm, rel)

        if args.write:
            target.parent.mkdir(parents=True, exist_ok=True)
            if not target.is_file() or target.read_text(encoding="utf-8") != expected:
                target.write_text(expected, encoding="utf-8", newline="\n")
                written += 1
            continue

        if not target.is_file():
            rep.error(f"{rel}: missing. studio-core defines it but this repo has no loader. "
                      "Run sync-loaders.sh.")
            continue

        actual = target.read_text(encoding="utf-8")
        if actual == expected:
            continue

        try:
            act_fm, _ = split_frontmatter(actual, rel)
        except ValueError as exc:
            rep.error(f"{rel}: {exc}. Run sync-loaders.sh.")
            continue

        drifted = [
            f"{k}: {act_fm.get(k, '(absent)')!r} != source {src_fm.get(k, '(absent)')!r}"
            for k in FRONTMATTER_KEYS
            if act_fm.get(k) != src_fm.get(k)
        ]
        if drifted:
            rep.error(f"{rel}: frontmatter drifted from {src.name} - " + "; ".join(drifted)
                      + ". Run sync-loaders.sh.")
        else:
            rep.error(f"{rel}: body is not the canonical loader body. A loader carries no "
                      "behaviour; move the content upstream to studio-core and run "
                      "sync-loaders.sh.")

    # Hook wiring, held to the same standard as a loader.
    settings_src = studio_core / SETTINGS_SRC
    settings_dst = project / SETTINGS_REL
    if settings_src.is_file():
        expected = settings_src.read_text(encoding="utf-8")
        if args.write:
            settings_dst.parent.mkdir(parents=True, exist_ok=True)
            if not settings_dst.is_file() or settings_dst.read_text(encoding="utf-8") != expected:
                settings_dst.write_text(expected, encoding="utf-8", newline="\n")
                written += 1
        elif not settings_dst.is_file():
            rep.error(f"{SETTINGS_REL}: missing. It wires the hook guards (scope, sequential, "
                      "git-tree, stop-state). Run sync-loaders.sh.")
        elif settings_dst.read_text(encoding="utf-8") != expected:
            rep.error(f"{SETTINGS_REL}: differs from studio-core's {SETTINGS_SRC}. Hook wiring "
                      "is not per-game; change it upstream and run sync-loaders.sh.")

    # Extra loaders: present here, defined nowhere upstream.
    claude_dir = project / ".claude"
    if claude_dir.is_dir():
        for existing in sorted(claude_dir.rglob("*.md")):
            rel = existing.relative_to(project).as_posix()
            if rel not in sources:
                rep.error(f"{rel}: no matching definition in studio-core. Either it was renamed "
                          "upstream, or this is a local fork of the harness. Delete it and run "
                          "sync-loaders.sh.")

    if args.write:
        total = len(sources) + (1 if settings_src.is_file() else 0)
        print(f"{green('loaders: synced')} - {written} written, "
              f"{total - written} already current")
        return EXIT_OK

    return rep.finish(f"{len(sources)} loader(s) match studio-core")


if __name__ == "__main__":
    raise SystemExit(main())
